"""Shared TikZ validation, wrapping, rendering, and image helpers."""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path

from PIL import Image

from agent.latex._tex import (
    _CONTROL_WORD_LETTERS,
    _FORBIDDEN_TEX_CONTROL_WORDS,
    _is_escaped,
    _without_tex_comments,
)

SUPPORTED_TIKZ_LIBRARIES = (
    "calc",
    "angles",
    "quotes",
    "intersections",
    "through",
    "positioning",
    "arrows.meta",
    "patterns",
)
SUPPORTED_TIKZ_PACKAGES = ("tkz-euclide",)

_UNSAFE_MODEL_TEX_ENVIRONMENTS = frozenset({"filecontents", "filecontents*"})


def validate_tikz(tikz: str) -> str:
    """Preflight one TikZ picture generated by the author model before compile."""
    cleaned = tikz.strip()
    if "\\begin{document}" in cleaned or "\\documentclass" in cleaned:
        raise ValueError("TikZ output must not contain a document wrapper.")
    if not cleaned.startswith(r"\begin{tikzpicture}") or not cleaned.endswith(
        r"\end{tikzpicture}"
    ):
        raise ValueError(
            "TikZ output must contain exactly one tikzpicture environment "
            "and no surrounding content."
        )
    if (
        cleaned.count("\\begin{tikzpicture}") != 1
        or cleaned.count("\\end{tikzpicture}") != 1
    ):
        raise ValueError(
            "TikZ output must contain exactly one tikzpicture environment."
        )

    uncommented = _without_tex_comments(cleaned)
    if uncommented != cleaned:
        raise ValueError("TikZ source must not contain comments; use blank lines to separate groups.")
    _validate_model_tikz_tex_subset(cleaned, uncommented)
    return cleaned


def _validate_model_tikz_tex_subset(source: str, uncommented: str) -> None:
    """Enforce the shared literal-source policy for model-authored TikZ.

    This is a defense-in-depth subset check, not a complete TeX sandbox. The
    compiler process still requires filesystem isolation from sensitive paths.
    """
    if "^^" in source:
        raise ValueError("TikZ output must not contain TeX character-code notation.")
    for name, argument in _iter_tex_control_words(uncommented):
        normalized = name.casefold()
        reason = _FORBIDDEN_TEX_CONTROL_WORDS.get(normalized)
        if reason:
            raise ValueError(
                f"TeX control sequence \\{name} is not allowed: {reason}; use public TikZ/PGF constructs."
            )
        if normalized in {"begin", "end"} and argument is not None:
            environment = "".join(argument.split()).casefold()
            if environment in _UNSAFE_MODEL_TEX_ENVIRONMENTS:
                raise ValueError(
                    f"TikZ output contains unsafe TeX environment {argument!r}."
                )


def _iter_tex_control_words(source: str) -> Iterator[tuple[str, str | None]]:
    """Lex literal TeX control words and their next braced argument."""
    index = 0
    while index < len(source):
        if source[index] != "\\" or index + 1 >= len(source):
            index += 1
            continue
        word_start = index + 1
        if source[word_start] not in _CONTROL_WORD_LETTERS:
            index += 2
            continue
        word_end = word_start + 1
        while word_end < len(source) and source[word_end] in _CONTROL_WORD_LETTERS:
            word_end += 1
        name = source[word_start:word_end]
        argument_start = word_end
        while argument_start < len(source) and source[argument_start].isspace():
            argument_start += 1
        argument = _literal_braced_argument(source, argument_start)
        yield name, argument
        index = word_end


def _literal_braced_argument(source: str, index: int) -> str | None:
    """Return one balanced literal group following a control word, if present."""
    if index >= len(source) or source[index] != "{":
        return None
    depth = 0
    cursor = index
    while cursor < len(source):
        character = source[cursor]
        if character in "{}" and not _is_escaped(source, cursor):
            depth += 1 if character == "{" else -1
            if depth == 0:
                return source[index + 1 : cursor]
        cursor += 1
    return None


def standalone_tikz_document(tikz: str) -> str:
    """Wrap an already-accepted TikZ picture in the fixed compile preamble."""
    return (
        "\\documentclass[tikz,border=4pt]{standalone}\n"
        "\\usepackage{amsmath,amssymb,mathtools}\n"
        + "".join(f"\\usepackage{{{package}}}\n" for package in SUPPORTED_TIKZ_PACKAGES)
        + f"\\usetikzlibrary{{{','.join(SUPPORTED_TIKZ_LIBRARIES)}}}\n"
        + "\\begin{document}\n"
        + f"{tikz.strip()}\n"
        + "\\end{document}\n"
    )


def crop_geometry_region(
    page_image_path: str | Path,
    *,
    bbox: list[float],
    page_size: list[float],
    output_path: str | Path,
    padding_pixels: int = 8,
) -> Path:
    """Crop one page-coordinate geometry region from a rendered page image."""
    if len(bbox) != 4 or len(page_size) != 2:
        raise ValueError(
            "bbox and page_size must contain four and two values respectively."
        )
    page_width, page_height = page_size
    if page_width <= 0 or page_height <= 0:
        raise ValueError("page_size values must be positive.")
    left, top, right, bottom = bbox
    if not (0 <= left < right <= page_width and 0 <= top < bottom <= page_height):
        raise ValueError("bbox must be ordered and contained within page_size.")
    source = Path(page_image_path).resolve()
    destination = Path(output_path).resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(source) as image:
        scale_x = image.width / page_width
        scale_y = image.height / page_height
        pixel_box = (
            max(0, round(left * scale_x) - padding_pixels),
            max(0, round(top * scale_y) - padding_pixels),
            min(image.width, round(right * scale_x) + padding_pixels),
            min(image.height, round(bottom * scale_y) + padding_pixels),
        )
        image.crop(pixel_box).save(destination)
    return destination
